-- Uygulama içi bildirim kutusu (ADR-022). Her bildirim bir (kullanıcı, tekilleştirme anahtarı) çiftine bağlıdır;
-- aynı olay ikinci kez yazılmaz (hatırlatmalar okuma sırasında üretilir, tekrar çağrı güvenlidir).
CREATE TABLE "wm-notifications" (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES "wm-uo-users"(id) ON DELETE CASCADE,
    kind       text        NOT NULL,
    title      text        NOT NULL,
    body       text        NOT NULL DEFAULT '',
    link       text        NOT NULL DEFAULT '',
    dedupe_key text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at    timestamptz,
    CONSTRAINT notifications_dedupe UNIQUE (user_id, dedupe_key)
);
CREATE INDEX notifications_user_time_idx ON "wm-notifications" (user_id, created_at DESC);

-- Salon–oturum uygunluğu (ADR-022): bir salon belirli bir oturumda kapalıysa (bakım, başka etkinlik) T-2 onu kullanmaz.
CREATE TABLE "wm-room_blocks" (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    bigint      NOT NULL REFERENCES "wm-rooms"(id) ON DELETE CASCADE,
    slot_id    bigint      NOT NULL REFERENCES "wm-slots"(id) ON DELETE CASCADE,
    reason     text        NOT NULL DEFAULT '' CHECK (char_length(reason) <= 200),
    created_by bigint      REFERENCES "wm-uo-users"(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT room_blocks_key UNIQUE (room_id, slot_id)
);

-- +goose Down
DROP TABLE IF EXISTS "wm-room_blocks";
DROP TABLE IF EXISTS "wm-notifications";

-- 6 haneli yoklama kodu için hatalı deneme kaydı. Önceden API sürecinin belleğindeydi; birden çok API
-- örneği çalıştığında her örnek ayrı sayıyordu ve yeniden başlatma sayacı sıfırlıyordu. Tablo,
-- "kullanıcı başına 5 dk'da 8 hatalı deneme" sınırını tüm örneklerde ortak ve kalıcı yapar.
-- Eski satırlar her yeni kayıtta o kullanıcı için silinir; tablo küçük kalır.
CREATE TABLE checkin_failures (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    failed_at timestamptz NOT NULL
);
CREATE INDEX checkin_failures_user_time_idx ON checkin_failures (user_id, failed_at);


-- Gözetmenin "Yeni QR oluştur" ile açtığı yoklama oturumu. Bir salon + slot için aynı anda tek açık oturum olur.
-- QR jetonu veritabanında tutulmaz (oturum kimliği + 30 sn'lik zaman penceresi üzerinden HMAC ile türetilir);
-- yedek 6 haneli kod burada durur ve gözetmen istediğinde yenilenir.
CREATE TABLE checkin_sessions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id     bigint      NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    slot_id         bigint      NOT NULL REFERENCES slots(id),
    room_id         bigint      NOT NULL REFERENCES rooms(id),
    started_by      bigint      NOT NULL REFERENCES users(id),
    code            text        NOT NULL CHECK (code ~ '^[0-9]{6}$'),
    code_expires_at timestamptz NOT NULL,
    started_at      timestamptz NOT NULL DEFAULT now(),
    ends_at         timestamptz NOT NULL,
    closed_at       timestamptz
);
CREATE UNIQUE INDEX checkin_sessions_open_key ON checkin_sessions (schedule_id, slot_id, room_id) WHERE closed_at IS NULL;


-- Kimlik ---------------------------------------------------------------
CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text        NOT NULL,
    password_hash text        NOT NULL,
    full_name     text        NOT NULL,
    active        boolean     NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_lower CHECK (email = lower(email)),
    CONSTRAINT users_email_key UNIQUE (email)
);

-- Bir kullanıcı birden çok rol taşıyabilir (öğretim üyesi + gözetmen, PROJECT_PLAN V-4).
CREATE TABLE user_roles (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role    text   NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT user_roles_role_check CHECK (
        role IN ('secretary','lecturer','invigilator','student_affairs','student'))
);

CREATE TABLE refresh_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash  bytea       NOT NULL,
    family_id   uuid        NOT NULL,           -- rotasyon zinciri; yeniden kullanım tespitinde tüm aile iptal edilir
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz,
    replaced_by bigint REFERENCES refresh_tokens(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT refresh_tokens_hash_key UNIQUE (token_hash)
);

-- Akademik veri --------------------------------------------------------
CREATE TABLE departments (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL
);

CREATE TABLE lecturers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    department_id bigint NOT NULL REFERENCES departments(id)
);

CREATE TABLE courses (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id bigint  NOT NULL REFERENCES departments(id),
    code          text    NOT NULL UNIQUE,
    name          text    NOT NULL,
    year          smallint NOT NULL CHECK (year BETWEEN 1 AND 6),
    requires_lab  boolean NOT NULL DEFAULT false
);

CREATE TABLE sections (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   bigint NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    code        text   NOT NULL,
    lecturer_id bigint NOT NULL REFERENCES lecturers(id),
    UNIQUE (course_id, code)
);

CREATE TABLE students (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint UNIQUE REFERENCES users(id) ON DELETE SET NULL, -- hesabı olmayan öğrenciler de var
    student_no      text    NOT NULL UNIQUE,
    full_name       text    NOT NULL,
    department_id   bigint  NOT NULL REFERENCES departments(id),
    disability_flag boolean NOT NULL DEFAULT false
);

CREATE TABLE enrollments (
    student_id bigint NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    section_id bigint NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
    PRIMARY KEY (student_id, section_id)
);

-- Salon envanteri ------------------------------------------------------
CREATE TABLE rooms (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       text     NOT NULL UNIQUE,
    building   text     NOT NULL,
    floor      smallint NOT NULL,
    type       text     NOT NULL,
    seat_rows  smallint NOT NULL,
    seat_cols  smallint NOT NULL,
    capacity   integer  NOT NULL,  -- aktif koltuk sayısı; room_seats ile tutarlılığı uygulama katmanında doğrulanır
    CONSTRAINT rooms_type_check     CHECK (type IN ('classic','lab')),
    CONSTRAINT rooms_capacity_check CHECK (capacity > 0),
    CONSTRAINT rooms_grid_check     CHECK (seat_rows > 0 AND seat_cols > 0),
    CONSTRAINT rooms_cap_le_grid    CHECK (capacity <= seat_rows * seat_cols)
);

CREATE TABLE room_seats (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id       bigint   NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    row_no        smallint NOT NULL CHECK (row_no >= 0),
    col_no        smallint NOT NULL CHECK (col_no >= 0),
    is_active     boolean  NOT NULL DEFAULT true,
    is_accessible boolean  NOT NULL DEFAULT false,
    UNIQUE (room_id, row_no, col_no),
    UNIQUE (room_id, id)          -- seat_assignments'ın (room_id, seat_id) bileşik FK'sı için
);

-- Dönem, slot, sınav ---------------------------------------------------
CREATE TABLE exam_periods (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text     NOT NULL UNIQUE,
    kind             text     NOT NULL CHECK (kind IN ('midterm','final')),
    start_date       date     NOT NULL,
    days             smallint NOT NULL CHECK (days > 0),
    sessions_per_day smallint NOT NULL CHECK (sessions_per_day > 0)
);

CREATE TABLE slots (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id     bigint   NOT NULL REFERENCES exam_periods(id) ON DELETE CASCADE,
    day_index     smallint NOT NULL CHECK (day_index >= 0),
    session_index smallint NOT NULL CHECK (session_index >= 0),
    starts_at     timestamptz NOT NULL,
    ends_at       timestamptz NOT NULL,
    UNIQUE (period_id, day_index, session_index),
    CHECK (ends_at > starts_at)
);

CREATE TABLE exams (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id        bigint  NOT NULL REFERENCES exam_periods(id) ON DELETE CASCADE,
    course_id        bigint  NOT NULL REFERENCES courses(id),
    duration_minutes smallint NOT NULL CHECK (duration_minutes BETWEEN 15 AND 300),
    requires_lab     boolean NOT NULL DEFAULT false,
    UNIQUE (period_id, course_id)
);

-- Çizelge ve planlar ---------------------------------------------------
CREATE TABLE schedules (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id    bigint      NOT NULL REFERENCES exam_periods(id) ON DELETE CASCADE,
    version      integer     NOT NULL CHECK (version > 0),
    status       text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
    seed         bigint      NOT NULL DEFAULT 42,
    metrics      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_by   bigint REFERENCES users(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,
    UNIQUE (period_id, version),
    CONSTRAINT schedules_published_at CHECK ((status = 'published') = (published_at IS NOT NULL))
);
-- Dönem başına en fazla bir yayınlanmış sürüm.
CREATE UNIQUE INDEX schedules_one_published_per_period
    ON schedules (period_id) WHERE status = 'published';

CREATE TABLE schedule_exams (
    schedule_id bigint NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    exam_id     bigint NOT NULL REFERENCES exams(id),
    slot_id     bigint NOT NULL REFERENCES slots(id),
    PRIMARY KEY (schedule_id, exam_id),
    UNIQUE (schedule_id, exam_id, slot_id)   -- alt tabloların slot tutarlılığı FK'sı için
);

CREATE TABLE room_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint NOT NULL,
    exam_id     bigint NOT NULL,
    slot_id     bigint NOT NULL REFERENCES slots(id),
    room_id     bigint NOT NULL REFERENCES rooms(id),
    seat_count  integer NOT NULL CHECK (seat_count > 0),
    UNIQUE (schedule_id, exam_id, room_id),
    -- slot_id, sınavın çizelgedeki slotuyla tutarlı olmak zorunda
    FOREIGN KEY (schedule_id, exam_id, slot_id) REFERENCES schedule_exams(schedule_id, exam_id, slot_id) ON DELETE CASCADE
);

-- Not: görev tanımındaki UNIQUE(schedule_id, room_id, seat_id) örneği, aynı salonun
-- farklı slotlarda kullanılmasını yanlışlıkla yasaklardı; bu yüzden slot_id anahtara eklendi (ADR-003).
CREATE TABLE seat_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint NOT NULL,
    exam_id     bigint NOT NULL,
    slot_id     bigint NOT NULL REFERENCES slots(id),
    student_id  bigint NOT NULL REFERENCES students(id),
    room_id     bigint NOT NULL REFERENCES rooms(id),
    seat_id     bigint NOT NULL,
    UNIQUE (schedule_id, slot_id, room_id, seat_id),   -- aynı slotta bir koltuk tek öğrenciye
    UNIQUE (schedule_id, exam_id, student_id),         -- her öğrenciye sınav başına tam bir koltuk
    FOREIGN KEY (schedule_id, exam_id, slot_id) REFERENCES schedule_exams(schedule_id, exam_id, slot_id) ON DELETE CASCADE,
    FOREIGN KEY (room_id, seat_id) REFERENCES room_seats(room_id, id)  -- koltuk gerçekten bu salonun
);

CREATE TABLE invigilator_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint NOT NULL,
    exam_id     bigint NOT NULL,
    slot_id     bigint NOT NULL REFERENCES slots(id),
    room_id     bigint NOT NULL REFERENCES rooms(id),
    user_id     bigint NOT NULL REFERENCES users(id),
    UNIQUE (schedule_id, slot_id, user_id),          -- aynı slotta iki görev yok
    UNIQUE (schedule_id, exam_id, room_id, user_id),
    FOREIGN KEY (schedule_id, exam_id, slot_id) REFERENCES schedule_exams(schedule_id, exam_id, slot_id) ON DELETE CASCADE
);

CREATE TABLE schedule_jobs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id   bigint NOT NULL REFERENCES exam_periods(id) ON DELETE CASCADE,
    status      text   NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','running','succeeded','failed')),
    params      jsonb  NOT NULL DEFAULT '{}'::jsonb,
    result      jsonb,
    error       text,
    schedule_id bigint REFERENCES schedules(id),
    created_by  bigint REFERENCES users(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    started_at  timestamptz,
    finished_at timestamptz
);

-- Mazeret ---------------------------------------------------------------
CREATE TABLE excuses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        text   NOT NULL CHECK (kind IN ('student','invigilator')),
    student_id  bigint REFERENCES students(id),
    user_id     bigint REFERENCES users(id),   -- gözetmen mazereti
    exam_id     bigint REFERENCES exams(id),   -- öğrenci mazereti
    slot_id     bigint REFERENCES slots(id),   -- gözetmen mazereti
    reason      text   NOT NULL,
    status      text   NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    decided_by  bigint REFERENCES users(id),
    decided_at  timestamptz,
    decision_note text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT excuses_shape CHECK (
        (kind = 'student'     AND student_id IS NOT NULL AND exam_id IS NOT NULL AND user_id IS NULL AND slot_id IS NULL) OR
        (kind = 'invigilator' AND user_id    IS NOT NULL AND slot_id IS NOT NULL AND student_id IS NULL AND exam_id IS NULL)),
    CONSTRAINT excuses_decided CHECK ((status = 'pending') = (decided_at IS NULL))
);

-- Yoklama ---------------------------------------------------------------
CREATE TABLE qr_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id        bigint NOT NULL REFERENCES exams(id),
    student_id     bigint NOT NULL REFERENCES students(id),
    token_hash     bytea  NOT NULL,                 -- yalnızca özet saklanır; ham token DB'ye girmez
    issued_at      timestamptz NOT NULL DEFAULT now(),
    expires_at     timestamptz NOT NULL,
    used_at        timestamptz,
    used_by_device text,
    revoked_at     timestamptz,
    CONSTRAINT qr_tokens_hash_key UNIQUE (token_hash),
    CONSTRAINT qr_tokens_used_consistent CHECK ((used_at IS NULL) = (used_by_device IS NULL))
);

CREATE TABLE attendance_events (
    event_id    uuid PRIMARY KEY,                   -- istemci üretir (UUIDv7); tekrar gönderim UNIQUE ile yok sayılır
    device_id   text   NOT NULL,
    exam_id     bigint NOT NULL REFERENCES exams(id),
    student_id  bigint NOT NULL REFERENCES students(id),
    status      text   NOT NULL CHECK (status IN ('present','absent')),
    source      text   NOT NULL CHECK (source IN ('qr','manual')),
    hlc_wall    bigint NOT NULL CHECK (hlc_wall >= 0),   -- hybrid logical clock: fiziksel bileşen (ms)
    hlc_counter integer NOT NULL CHECK (hlc_counter >= 0),
    recorded_by bigint REFERENCES users(id),
    received_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE attendance_state (
    exam_id     bigint NOT NULL REFERENCES exams(id),
    student_id  bigint NOT NULL REFERENCES students(id),
    status      text   NOT NULL CHECK (status IN ('present','absent')),
    source      text   NOT NULL CHECK (source IN ('qr','manual')),
    device_id   text   NOT NULL,
    hlc_wall    bigint NOT NULL,
    hlc_counter integer NOT NULL,
    event_id    uuid   NOT NULL REFERENCES attendance_events(event_id),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (exam_id, student_id)
);

CREATE TABLE attendance_conflicts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id         bigint NOT NULL REFERENCES exams(id),
    student_id      bigint NOT NULL REFERENCES students(id),
    winner_event_id uuid   NOT NULL REFERENCES attendance_events(event_id),
    loser_event_id  uuid   NOT NULL REFERENCES attendance_events(event_id),
    rule            text   NOT NULL CHECK (rule IN ('qr_present','hlc','device_id')),
    detected_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (winner_event_id, loser_event_id),
    CHECK (winner_event_id <> loser_event_id)
);

CREATE TABLE room_change_events (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id  bigint NOT NULL REFERENCES schedules(id),
    slot_id      bigint NOT NULL REFERENCES slots(id),
    from_room_id bigint NOT NULL REFERENCES rooms(id),
    to_room_id   bigint NOT NULL REFERENCES rooms(id),
    reason       text   NOT NULL,
    moved_count  integer NOT NULL CHECK (moved_count >= 0),
    actor_id     bigint REFERENCES users(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (from_room_id <> to_room_id)
);

-- Denetim ve idempotency ------------------------------------------------
CREATE TABLE audit_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id   bigint,                              -- bilinçli olarak FK yok: kullanıcı silinse de kayıt kalır
    action     text   NOT NULL,
    entity     text   NOT NULL,
    entity_id  text   NOT NULL,
    old_value  jsonb,
    new_value  jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE idempotency_keys (
    key          text   NOT NULL,
    user_id      bigint NOT NULL,
    method_path  text   NOT NULL,
    request_hash bytea  NOT NULL,
    state        text   NOT NULL DEFAULT 'in_progress' CHECK (state IN ('in_progress','done')),
    status       integer,
    body         bytea,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (key, user_id)
);

-- Seed işaretçisi: seed komutunu tekrar çalıştırmanın güvenli olması için.
CREATE TABLE seed_meta (
    id           boolean PRIMARY KEY DEFAULT true CHECK (id),  -- tek satır
    seed         bigint NOT NULL,
    dataset_hash text   NOT NULL,
    seeded_at    timestamptz NOT NULL DEFAULT now()
);

